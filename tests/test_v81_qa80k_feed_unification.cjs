'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs');
const acct=require('../www/pfm-v81-accounting-core.js');
const filename='www/pfm-v81-qa80k.json';
assert(fs.existsSync(filename),'80k dataset MUST be bundled in this QA build');
const db=JSON.parse(fs.readFileSync(filename,'utf8'));
assert.equal(db.qaOnly,true);
assert.equal(db.settings.localOnly,true);
assert.equal(db.farms.length,2);
assert.equal(db.houses.length,4);
assert.equal(db.cycles.length,4);
assert.equal(db.cycles.reduce((sum,c)=>sum+c.birds,0),80000);
assert(db.cycles.every(c=>c.birds===20000));
assert(db.farms.every(f=>db.houses.filter(h=>h.farmId===f.id).length===2));
assert(db.houses.every(h=>db.cycles.some(c=>c.houseId===h.id)));
assert.equal(db.v410.purchaseDocuments.length,34);
assert.equal(db.v410.movements.length,32);
assert.equal(db.daily.length,168);
assert.equal(db.sales.length,8);
assert.deepEqual(acct.validateLedger(db),[]);
const farmIds=new Set(db.farms.map(f=>f.id));
for(const doc of db.v410.purchaseDocuments)assert(farmIds.has(doc.farmId));
for(const lot of db.v410.lots)assert(farmIds.has(lot.farmId));
for(const move of db.v410.movements){
 const lot=db.v410.lots.find(l=>l.id===move.lotId);
 const cycle=db.cycles.find(c=>c.id===move.cycleId);
 assert(lot&&cycle,'all issues link a real lot and cycle');
 assert.equal(lot.farmId,cycle.farmId,'no cross-farm feed issues');
}
const html=fs.readFileSync('www/index.html','utf8');
const invoice=fs.readFileSync('www/pfm-v8-invoice-ui.js','utf8');
const nav=fs.readFileSync('www/pfm-v8-purchases-workspace.js','utf8');
const sandbox=fs.readFileSync('www/pfm-v81-qa80k-profile.js','utf8');
const one=fs.readFileSync('www/pfm-v8-one-page-purchases.js','utf8');
const legacy=fs.readFileSync('www/pfm-v75-android-purchases.js','utf8');
assert(!html.includes('<script src="./pfm-v68-sa-training.js"></script>'));
assert(html.includes('pfm-v81-qa80k-profile.js'));
assert(invoice.includes('اختر المزرعة قبل الشراء'));
assert(invoice.includes('المزرعة المشترية *'));
assert(invoice.includes('if(!farm())throw Error'));
assert(nav.includes("content:none!important"),'sidebar pseudo-title must not duplicate text');
assert(nav.includes('btn.textContent=title'),'side menu has one title');
assert(one.includes("if(page==='feed')page='inventory'"));
assert(html.includes("if(window.PFMV8SingleEntryActive)return alert("),'legacy price writer must be blocked');
assert(sandbox.includes('window.PFMV63.persist(QA_ID,KEY,baseline)'),'canonical QA reset must overwrite test profile on entry only');
assert(sandbox.includes('persistLocal()'),'original account must be stored before switching');
assert(sandbox.includes("stopV8Realtime()"),'cloud realtime must stop before local QA starts');
assert(html.includes('if(hasRealSupabaseConfig()&&!inQAProfile)'), 'QA must skip Supabase startup');
assert(html.includes("if(currentUser?.id==='pfm-v81-qa-80k-local'||db?.qaOnly)return"), 'QA must never sync cloud');
assert(sandbox.includes("pfm-v81-qa80k-origin-session"),'restore original session');
assert(legacy.includes("n.textContent='المشتريات والمخزون'"));
console.log('PASS: real 80K farm scenario bundled, ledgers cross-check, explicit purchasing farm and isolated offline test profile');
