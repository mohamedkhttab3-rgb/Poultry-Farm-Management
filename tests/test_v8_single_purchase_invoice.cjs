'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs');
const invoice=require('../www/pfm-v8-invoice-core.js');
const purchase=require('../www/pfm-v74-purchase-core.js');
let seq=0;
const ctx={uuid:()=> 'synthetic-'+String(++seq),price:purchase.price,shares:purchase.shares,
 normalizeExpenses:f=>Array.isArray(f.expenses)&&f.expenses.length?f.expenses:(f.labor?[{id:'old',category:'عمال',amount:f.labor}]:[]),
 canFinance:()=>true,cycleOrdinal:c=>c.cycleNumber,userId:'test-only',now:()=> '2026-10-20T09:00:00Z'};
const blank=()=>({farms:[{id:'f1'}],cycles:[{id:'c1',farmId:'f1',houseId:'h1',cycleNumber:1,birds:100},{id:'c2',farmId:'f1',houseId:'h2',cycleNumber:1,birds:200}],
 finance:{c1:{labor:40,otherRevenue:50}},v410:{lots:[],chicks:{},expenses:{},audit:[],movements:[],close:{}},settings:{currency:'SAR'}});
const feed={kind:'feed',item:'بادي',quantity:1000,unit:'kg',amount:2000,vatRate:15,reclaim:100};
const chick={kind:'chicks',item:'صيصان',quantity:300,unit:'item',priceMode:'unit',amount:2,free:10,cycleNumber:1,vatRate:15,reclaim:100};
const med={kind:'med',item:'دواء',quantity:100,unit:'dose',amount:300,vatRate:15,reclaim:50};
const transport={kind:'transport',item:'نقل',quantity:1,amount:230,cycleId:'c1',vatMode:'included',vatRate:15,reclaim:0};
const request=(lines=[feed,chick,med,transport])=>({farmId:'f1',supplier:'Supplier One',invoice:'123',date:'2026-10-20',lines});
const db=blank(),before=JSON.stringify(db),p=invoice.prepare(db,request(),ctx);
assert.equal(JSON.stringify(db),before,'Preview must be read-only');
assert.equal(p.nextV410.lots.length,2,'Feed and medicine create lots, not duplicate expenses');
assert.equal(p.nextV410.movements.length,0,'No inventory issue at purchase time');
assert.equal(p.nextFinance.c1.expenses.length,2,'Keep old expense once and add transport once');
assert.equal(p.nextFinance.c1.expenses[0].amount,40);
assert.equal(p.nextFinance.c1.expenses[1].amount,230);
assert.equal(p.nextFinance.c1.otherRevenue,50);
assert.equal(p.nextFinance.c1.chicks+p.nextFinance.c2.chicks,580);
assert.equal(p.nextV410.chicks.c1.free+p.nextV410.chicks.c2.free,10);
assert.equal(p.document.totals.accountingCost,3132.5);
let saves=0;invoice.commit(db,request(),{...ctx,persist:()=>saves++});
assert.equal(saves,1);
assert.equal(db.v410.purchaseDocuments.length,1);
assert.throws(()=>invoice.prepare(db,request(),ctx),/DUPLICATE_INVOICE/);
assert.throws(()=>invoice.prepare(blank(),request([feed,{...feed}]),ctx),/DUPLICATE_ITEM/);
assert.throws(()=>invoice.prepare(blank(),request([{...feed,item:'عام'}]),ctx),/Feed purchase must specify/);
const tons=invoice.prepare(blank(),request([{...feed,item:'نامي',quantity:2,unit:'ton',amount:2000}]),ctx);
assert.equal(tons.document.lines[0].quantity,2,'Invoice must retain source quantity');
assert.equal(tons.document.lines[0].unit,'ton','Invoice must retain original ton unit');
assert.equal(tons.nextV410.lots[0].qty,2000,'Stock must convert tons to kg');
assert.equal(tons.nextV410.lots[0].unit,'kg','Stock unit must be kg');
assert.equal(tons.nextV410.lots[0].unitCost,1,'Purchase value per stock kg');
assert.throws(()=>invoice.prepare(blank(),{...request(),date:'2026-02-31'},ctx),/Valid invoice date/);
assert.throws(()=>invoice.prepare(blank(),{...request(),date:'bad'},ctx),/Valid invoice date/);
assert.throws(()=>invoice.prepare(blank(),request([chick]),{...ctx,currency:()=> 'USD'}),/CURRENCY_MISMATCH/);
assert.throws(()=>invoice.prepare(blank(),request([transport]),{...ctx,currency:()=> 'USD'}),/CURRENCY_MISMATCH/);
assert.throws(()=>invoice.prepare(blank(),request([chick,{...chick,item:'صيصان أخرى'}]),ctx),/DUPLICATE_CHICKS/);
assert.throws(()=>invoice.prepare(blank(),request([{...chick,quantity:299}]),ctx),/must equal the total received/);
const legacy=blank();legacy.v410.lots.push({farmId:'f1',supplier:'Supplier One',invoice:'123',item:'بادي'});
assert.throws(()=>invoice.prepare(legacy,request(),ctx),/DUPLICATE_INVOICE/);
const legacyChick=blank();legacyChick.v410.purchaseInvoices=[{farmId:'f1',supplier:'Supplier One',invoice:'123'}];
assert.throws(()=>invoice.prepare(legacyChick,request(),ctx),/DUPLICATE_INVOICE/);
const closed=blank();closed.v410.close.c1={status:'closed'};
assert.throws(()=>invoice.prepare(closed,request([transport]),ctx),/closed/);
const failed=blank(),snapshot=JSON.stringify(failed);
assert.throws(()=>invoice.commit(failed,request([feed]),{...ctx,persist:()=>{throw Error('Storage full')}}),/Storage full/);
assert.equal(JSON.stringify(failed),snapshot,'Rollback on failed durable write');
assert.throws(()=>invoice.prepare(blank(),request(),{...ctx,canFinance:()=>false}),/Finance permission/);
const ui=fs.readFileSync('www/pfm-v8-invoice-ui.js','utf8'),html=fs.readFileSync('www/index.html','utf8');
assert(ui.includes('PFMV8InvoiceCore.commit'));
assert(ui.includes('class="v8-feed"'));
assert(ui.includes('#finance [onclick="addFinanceExpense()"]'));
assert(html.includes('pfm-v8-invoice-core.js')&&html.includes('pfm-v8-invoice-ui.js'));
console.log('PASS: invoice accounting, one-time stock cost, chicks, legacy preservation, VAT, duplicates, closed cycles, permissions, persistence rollback.');
